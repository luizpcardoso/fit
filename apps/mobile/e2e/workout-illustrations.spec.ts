import { test, expect as baseExpect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { waitForApiBudget } from './helpers/api-budget';

const expect = baseExpect.configure({ timeout: 20000 });
const apiURL = process.env.FIT_E2E_API_URL ?? 'http://127.0.0.1:33329';
for (const theme of ['light', 'dark']) test(`ilustrações por treino são escolhidas, salvas e editadas: ${theme}`, async ({ page, request }) => {
  test.setTimeout(180000);
  test.skip(process.env.FIT_WORKOUT_ILLUSTRATIONS_E2E !== '1', 'Requer API local com banco temporário isolado.');
  if (!['127.0.0.1', 'localhost'].includes(new URL(apiURL).hostname)) throw new Error('Use somente uma API local de testes.');
  await waitForApiBudget(request, apiURL);
  const registered = await request.post(apiURL + '/auth/register', { data: { email: `illustrations-${randomUUID()}@example.com`, password: 'integration-test-123', phone: '71999990000', firstName: 'Teste', lastName: 'Ilustração' } });
  expect(registered.status()).toBe(201);
  const account = await registered.json(), headers = { authorization: `Bearer ${account.accessToken}` };
  await page.route(/http:\/\/[^/]+:(?:3333|33329)\//, route => route.continue({ url: apiURL + new URL(route.request().url()).pathname + new URL(route.request().url()).search }));
  await page.addInitScript(({ account, theme }) => { localStorage.setItem('fit.auth.tokens', JSON.stringify(account)); localStorage.setItem('fit.appearance.theme', theme); }, { account, theme });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && message.text().includes('Unexpected text node')) errors.push(message.text()); });
  page.setDefaultTimeout(20000); page.setDefaultNavigationTimeout(60000);
  await page.goto('/workout-create', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: /Criar minha ficha/ }).click();
  await page.getByRole('radio', {name: 'Força', exact: true}).click();
  await page.getByRole('radiogroup', {name: 'Imagem da ficha', exact: true}).screenshot({path: `artifacts/ux-review/workout-illustrations/covers-${theme}.png`});
  await page.getByLabel('Nome da ficha', { exact: true }).fill('Ficha com ilustrações');
  await page.getByLabel('Nome do treino A', { exact: true }).fill('Costas e ombros');
  const initial = page.getByRole('button', { name: 'Imagem do treino A: sem ilustração', exact: true });
  const height = (await initial.boundingBox())!.height;
  await initial.click();
  await expect(page.getByRole('radiogroup', { name: 'Ilustrações disponíveis', exact: true })).toBeVisible();
  await expect(page.getByRole('radiogroup', { name: 'Ilustrações disponíveis', exact: true }).getByRole('radio')).toHaveCount(14);
  expect(await page.locator('input[type=file]').count()).toBe(0);
  await page.screenshot({ animations: 'disabled', path: `artifacts/ux-review/workout-illustrations/picker-${theme}.png` });
  await page.getByRole('radio', { name: 'Costas + ombros', exact: true }).click();
  const selected = page.getByRole('button', { name: 'Imagem do treino A: Costas + ombros', exact: true });
  await expect(selected).toBeVisible();
  expect((await selected.boundingBox())!.height).toBe(height);
  await selected.click();
  await expect(page.getByRole('radio', { name: 'Costas + ombros', exact: true })).toBeChecked();
  await page.getByRole('radio', { name: 'Sem ilustração', exact: true }).click();
  expect((await initial.boundingBox())!.height).toBe(height);
  await initial.click();
  await page.getByRole('radio', { name: 'Costas + ombros', exact: true }).click();
  expect(await (await request.get(apiURL + '/workout-plans', { headers })).json()).toHaveLength(0);
  const addExercise = async (letter: string, name: string) => {
    await page.getByRole('button', { name: `Adicionar exercícios ao treino ${letter}`, exact: true }).click();
    await page.getByPlaceholder('Ex.: Remada unilateral no cabo').fill(name);
    await page.getByText('Selecionar personalizado', { exact: true }).click();
    await page.getByRole('button', { name: `Adicionar 1 exercício ao treino ${letter}`, exact: true }).click();
  };
  await addExercise('A', 'Remada visual');
  await page.getByRole('tab', { name: 'Treino B', exact: true }).click();
  await page.getByLabel('Nome do treino B', { exact: true }).fill('Peito e ombros');
  await page.setViewportSize({ width: 320, height: 740 });
  await page.getByRole('button', { name: 'Imagem do treino B: sem ilustração', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ animations: 'disabled', path: `artifacts/ux-review/workout-illustrations/picker-${theme}-320.png` });
  await page.getByRole('radio', { name: 'Peito + ombros', exact: true }).click();
  await addExercise('B', 'Supino visual');
  await page.setViewportSize({ width: 390, height: 844 });
  const created = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/workout-plans');
  await page.getByRole('button', { name: 'Salvar ficha', exact: true }).click();
  const saved = await created; expect(saved.status()).toBe(201);
  const id = (await saved.json()).id;
  const plan = await (await request.get(`${apiURL}/workout-plans/${id}`, { headers })).json();
  expect(plan.coverId).toBe('strength');
  expect(plan.divisions.map((d: { illustrationId: string }) => d.illustrationId)).toEqual(['back-shoulders', 'chest-shoulders']);
  await page.goto('/workouts');
  await expect(page.getByText('Ficha ativa', {exact: true})).toBeVisible();
  await page.screenshot({path: `artifacts/ux-review/workout-illustrations/fitness-${theme}.png`});
  await page.goto(`/workout-detail?id=${id}`);
  await expect(page.getByRole('img', { name: 'Ilustração de Costas + ombros', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: /Peito e ombros/ }).click();
  await expect(page.getByRole('img', { name: 'Ilustração de Peito + ombros', exact: true })).toBeVisible();
  await page.screenshot({ path: `artifacts/ux-review/workout-illustrations/detail-${theme}.png`, fullPage: true });
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: `artifacts/ux-review/workout-illustrations/detail-${theme}-320.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`/workout-create?id=${id}`);
  await page.getByRole('button', { name: 'Imagem do treino A: Costas + ombros', exact: true }).click();
  await page.getByRole('radio', { name: 'Costas', exact: true }).click();
  const updated = page.waitForResponse(response => response.request().method() === 'PUT' && new URL(response.url()).pathname === `/workout-plans/${id}`);
  await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
  expect((await updated).status()).toBe(200);
  const edited = await (await request.get(`${apiURL}/workout-plans/${id}`, { headers })).json();
  expect(edited.divisions.map((d: { illustrationId: string }) => d.illustrationId)).toEqual(['back', 'chest-shoulders']);
  expect(edited.divisions.map((d: { exercises: unknown[] }) => d.exercises)).toEqual(plan.divisions.map((d: { exercises: unknown[] }) => d.exercises));
  await page.goto(`/workout-run?planId=${id}&divisionId=${plan.divisions[0].id}`);
  await expect(page.getByRole('img', { name: 'Ilustração de Costas', exact: true })).toBeVisible();
  await page.screenshot({ path: `artifacts/ux-review/workout-illustrations/start-${theme}.png`, fullPage: true });
  expect(await (await request.get(apiURL + '/workout-runs/active', { headers })).json()).toBeNull();
  expect(errors).toEqual([]);
});
