import { waitForApiBudget } from './helpers/api-budget';
import { test, expect as baseExpect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
const apiURL = process.env.FIT_E2E_API_URL ?? 'http://127.0.0.1:33329';
// Allow development bundles and encrypted recovery to settle on a busy build host.
const expect = baseExpect.configure({ timeout: 20000 });
for (const theme of ['light', 'dark']) test(`Home mantém treino ativo e permite conclusão por exercício: ${theme}`, async ({ page, request }) => {
  test.setTimeout(240000);
  page.setDefaultTimeout(20000);
  page.setDefaultNavigationTimeout(60000);
  test.skip(process.env.FIT_WORKOUT_RUN_E2E !== '1', 'Use API e banco isolados para esta verificação.');
  if (!['127.0.0.1', 'localhost'].includes(new URL(apiURL).hostname)) throw new Error('Use somente API local de testes.');
  await waitForApiBudget(request, apiURL);
  const registered = await request.post(`${apiURL}/auth/register`, { data: { email: `run-${randomUUID()}@example.com`, password: 'integration-test-123', phone: '71999990000', firstName: 'Teste', lastName: 'Treino' } });
  expect(registered.status()).toBe(201);
  const account = await registered.json();
  const headers = { authorization: `Bearer ${account.accessToken}` };
  const created = await request.post(`${apiURL}/workout-plans`, { headers, data: { name: 'Minha ficha guiada', divisions: [{ name: 'Peito e costas', exercises: [{ name: 'Supino teste', sets: 3, reps: '12', restSeconds: 60 }, { name: 'Remada teste', sets: 2, reps: '10' }] }, { name: 'Pernas', exercises: [{ name: 'Agachamento teste', sets: 3, reps: '12' }] }, { name: 'Ombros', exercises: [{ name: 'Desenvolvimento teste', sets: 3, reps: '10' }] }] } });
  expect(created.status()).toBe(201);
  const plan = await (await request.get(`${apiURL}/workout-plans/${(await created.json()).id}`, { headers })).json();
  const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Bahia', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
  const weekday = ((new Date(`${today}T12:00:00Z`).getUTCDay() + 6) % 7) + 1;
  const goal = await request.put(`${apiURL}/workout-goal`, { headers, data: { weeklyTarget: 1, mode: 'planned', schedule: [{ weekday, divisionId: plan.divisions[2].id }] } });
  expect(goal.status()).toBe(204);
  let offline = false;
  // Metro may retain the device .env URL; route the app transport to the isolated local API.
  await page.route(/http:\/\/[^/]+:(?:3333|33329)\//, route => offline ? route.abort('internetdisconnected') : route.continue({ url: `${apiURL}${new URL(route.request().url()).pathname}${new URL(route.request().url()).search}` }));
  await page.addInitScript(({ account, theme }) => { localStorage.setItem('fit.auth.tokens', JSON.stringify(account)); localStorage.setItem('fit.appearance.theme', theme); }, { account, theme });
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && message.text().includes('Unexpected text node')) errors.push(message.text()); });
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await expect(page.getByText('0 de 1 feitas', { exact: true })).toBeVisible({ timeout: 30000 });
  await page.getByRole('button', { name: 'Ver atividades de hoje', exact: true }).click();
  await expect(page.getByText('Treino planejado para hoje', { exact: true })).toHaveCount(0);
  await expect(page.getByText('Check-in da Mente', { exact: true })).toBeVisible();
  await page.goto(`/workout-run?planId=${plan.id}`);
  await expect(page.getByRole('button', { name: 'Iniciar treino C', exact: true })).toBeVisible({ timeout: 30000 });
  await expect(page.getByText('O cronômetro começa ao iniciar', { exact: true })).toBeVisible();
  expect(await (await request.get(`${apiURL}/workout-runs/active`, { headers })).json()).toBeNull();
  await page.screenshot({ path: `artifacts/ux-review/workout-start-${theme}.png` });
  await page.getByRole('button', { name: 'Escolher outro treino', exact: true }).click();
  await page.getByRole('radio', { name: 'Treino A, Peito e costas, Minha ficha guiada', exact: true }).click();
  await expect(page.getByText('Supino teste', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Iniciar treino A', exact: true }).click();
  const card = page.getByTestId('workout-exercise-card');
  const primary = page.getByTestId('complete-exercise-button');
  const before = await card.boundingBox();
  await expect(primary).toHaveAccessibleName('Concluir série 1 de 3');
  await primary.click();
  await expect(page.getByLabel('1 de 3 séries concluídas', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Pular descanso', exact: true })).toBeVisible();
  expect((await card.boundingBox())!.height).toBe(before!.height);
  await page.getByRole('checkbox', { name: 'Série 1 concluída', exact: true }).click();
  await expect(page.getByLabel('0 de 3 séries concluídas', { exact: true })).toBeVisible();
  expect((await card.boundingBox())!.height).toBe(before!.height);
  await page.getByLabel('Carga de Supino teste, em quilos', { exact: true }).fill('40');
  await primary.click();
  await expect(page.getByLabel('1 de 3 séries concluídas', { exact: true })).toBeVisible();
  await expect(page.getByLabel(/Tempo total do treino/).first()).toBeVisible();
  await page.goto('/');
  const banner = page.getByTestId('workout-mini-player');
  await expect(banner).toBeInViewport();
  await expect(banner).toContainText('Treino A em andamento');
  await expect(banner).toContainText('1 de 5 séries');
  await expect(page.getByRole('button', { name: 'Continuar treino A', exact: true }).first()).toBeVisible();
  const bannerTop = (await banner.boundingBox())!.y;
  await page.getByTestId('home-scroll').evaluate(element => { element.scrollTop = element.scrollHeight; });
  await expect(banner).toBeInViewport();
  expect((await banner.boundingBox())!.y).toBe(bannerTop);
  await page.setViewportSize({ width: 320, height: 740 });
  await expect(banner).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: `artifacts/ux-review/workout-home-${theme}-320.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await banner.click();
  await expect(page.getByLabel('1 de 3 séries concluídas', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Carga de Supino teste, em quilos', { exact: true })).toHaveValue('40');
  await page.getByRole('button', { name: '2. Remada teste, 0 de 2 séries', exact: true }).click();
  await expect(page.getByText('Exercício 2 de 2', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Exercício 2 de 2', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '1. Supino teste, 1 de 3 séries', exact: true }).click();
  await expect(page.getByLabel('1 de 3 séries concluídas', { exact: true })).toBeVisible();
  offline = true;
  await primary.click();
  await expect(page.getByLabel('2 de 3 séries concluídas', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Pausar treino', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Retomar treino', exact: true })).toBeVisible();
  await expect(page.getByText('Pausado', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Retomar treino', exact: true })).toBeVisible();
  await expect(page.getByLabel('2 de 3 séries concluídas', { exact: true })).toBeVisible();
  await page.goto('/');
  await expect(banner).toBeInViewport();
  await expect(banner).toContainText('Treino A pausado');
  await expect(banner).toContainText('2 de 5 séries');
  await banner.click();
  await expect(page.getByRole('checkbox', { name: 'Série 3 pendente', exact: true })).toBeDisabled();
  await page.screenshot({ path: `artifacts/ux-review/workout-run-${theme}-offline.png`, fullPage: true });
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(page.getByRole('button', { name: 'Retomar treino', exact: true })).toBeInViewport();
  await expect(page.getByText('Supino teste', { exact: true })).toBeInViewport();
  await page.screenshot({ path: `artifacts/ux-review/workout-run-${theme}-320.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  offline = false;
  await page.getByRole('button', { name: 'Opções do treino', exact: true }).click();
  await page.getByRole('button', { name: 'Sincronizar agora', exact: true }).click();
  await expect(page.getByText('Sincronizado com sua conta.', { exact: true })).toBeVisible({ timeout: 20000 });
  await page.getByRole('button', { name: 'Fechar', exact: true }).click();
  await page.getByRole('button', { name: 'Retomar treino', exact: true }).click();
  await page.getByRole('button', { name: 'Finalizar treino agora', exact: true }).click();
  await expect(page.getByText('Finalizar treino parcial?', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Finalizar treino', exact: true }).last().click();
  await expect(page.getByText('Treino finalizado', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Concluir', exact: true })).toBeEnabled({ timeout: 20000 });
  await expect(page.getByText('Remada teste', { exact: true })).toBeVisible();
  const history = await (await request.get(`${apiURL}/workout-sessions`, { headers })).json();
  expect(history).toHaveLength(1);
  expect(history[0].execution.completedExercises).toBe(0);
  expect(history[0].execution.completedSets).toBe(2);
  const previous = await (await request.get(`${apiURL}/workout-runs/previous?divisionId=${plan.divisions[0].id}`, { headers })).json();
  expect(previous[plan.divisions[0].exercises[0].id][0]).toEqual({ set: 0, loadKg: 40, reps: 12 });
  await page.goto('/');
  await expect(page.getByText('0 de 1 feitas', { exact: true })).toBeVisible();
  await expect(page.getByLabel('1 de 1 treinos nesta semana. Meta da semana concluída.', { exact: true })).toBeVisible();
  await expect(banner).toHaveCount(0);
  const summary = await (await request.get(`${apiURL}/me/daily-summary?date=${today}`, { headers })).json();
  expect(summary.checks).toEqual({ completed: 0, total: 1 });
  expect(summary.categories.find((item: {kind:string}) => item.kind === 'workout').completed).toBe(1);
  await page.goto(`/session-edit?id=${history[0].id}`);
  await expect(page.getByText(/^Supino teste: 2\/3 séries · 40 kg × 12/)).toBeVisible({ timeout: 30000 });
  await page.screenshot({ path: `artifacts/ux-review/workout-run-${theme}-history.png`, fullPage: true });
  // Complete whole exercises from the exercise menu, undo to the partial state, and recover completion offline.
  await waitForApiBudget(request, apiURL);
  await page.goto(`/workout-run?planId=${plan.id}&divisionId=${plan.divisions[0].id}`);
  await page.getByRole('button', { name: 'Iniciar treino A', exact: true }).click();
  await expect(page.getByLabel('Carga de Supino teste, em quilos', { exact: true })).toHaveValue('40', { timeout: 20000 });
  await primary.click();
  await expect(page.getByLabel('1 de 3 séries concluídas', { exact: true })).toBeVisible();
  const partialHeight = (await card.boundingBox())!.height;
  const exerciseMenu = () => page.getByRole('button', { name: /^Mais ações para / }).click();
  await exerciseMenu();
  await page.getByRole('button', { name: /^Concluir todas as séries/ }).click();
  await expect(page.getByLabel('3 de 3 séries concluídas', { exact: true })).toBeVisible();
  expect((await card.boundingBox())!.height).toBe(partialHeight);
  await exerciseMenu();
  await page.getByRole('button', { name: /^Desfazer conclusão do exercício/ }).click();
  await expect(page.getByLabel('1 de 3 séries concluídas', { exact: true })).toBeVisible();
  expect((await card.boundingBox())!.height).toBe(partialHeight);
  offline = true;
  await exerciseMenu();
  await page.getByRole('button', { name: /^Concluir todas as séries/ }).click();
  await page.reload();
  await expect(page.getByLabel('3 de 3 séries concluídas', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Pular descanso', exact: true })).toHaveCount(0);
  offline = false;
  await page.getByRole('button', { name: 'Opções do treino', exact: true }).click();
  await page.getByRole('button', { name: 'Sincronizar agora', exact: true }).click();
  await expect(page.getByText('Sincronizado com sua conta.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Fechar', exact: true }).click();
  await expect(primary).toHaveAccessibleName('Próximo exercício');
  await primary.click();
  await expect(page.getByText('Exercício 2 de 2', { exact: true })).toBeVisible();
  await exerciseMenu();
  await page.getByRole('button', { name: /^Concluir todas as séries/ }).click();
  await expect(page.getByLabel('2 de 2 séries concluídas', { exact: true })).toBeVisible();
  await page.screenshot({ path: `artifacts/ux-review/workout-complete-${theme}.png`, fullPage: true });
  await expect(primary).toHaveAccessibleName('Finalizar treino');
  await primary.click();
  await expect(page.getByText('Finalizar treino completo?', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Finalizar treino', exact: true }).last().click();
  await expect(page.getByText('Treino completo!', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Concluir', exact: true })).toBeEnabled({ timeout: 20000 });
  const allHistory = await (await request.get(`${apiURL}/workout-sessions`, { headers })).json();
  expect(allHistory).toHaveLength(2);
  expect(allHistory.some((entry: { execution: { completedExercises: number; completedSets: number } }) => entry.execution.completedExercises === 2 && entry.execution.completedSets === 5)).toBe(true);
  await page.getByRole('button', { name: 'Iniciar outro treino', exact: true }).click();
  await expect(page.getByText('Qual treino vamos fazer?', { exact: true })).toBeVisible();
  expect(await (await request.get(`${apiURL}/workout-runs/active`, { headers })).json()).toBeNull();
  expect(errors).toEqual([]);
});
